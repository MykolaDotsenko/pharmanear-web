/**
 * The first supported language in the visitor's browser preferences, else English.
 * Only the primary subtag matters: `sv-FI` and `sv-SE` both select Swedish.
 */
export function preferredLanguage(requested = []) {
  for (const tag of requested) {
    const language = String(tag).toLowerCase().split('-')[0];
    if (Object.hasOwn(messages, language)) return language;
  }
  return 'en';
}
